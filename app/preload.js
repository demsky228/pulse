  sessionCurrent: call('sessionCurrent'),
  logError: call('logError'),
  diagInfo: call('diagInfo'),
  openLogs: call('openLogs'),
  appVersion: call('appVersion'),
  diskScan: call('diskScan'),
  diskNode: call('diskNode'),
  diskCancel: call('diskCancel'),
